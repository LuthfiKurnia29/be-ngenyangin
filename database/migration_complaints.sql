-- Admin-managed records of complaints received by phone or other offline channels.
BEGIN;

CREATE TABLE IF NOT EXISTS public.complaints (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_role text NOT NULL CHECK (reporter_role IN ('consumer', 'supplier')),
  reporter_name text NOT NULL,
  reporter_phone text NOT NULL,
  title text NOT NULL,
  category text NOT NULL,
  priority text NOT NULL DEFAULT 'Sedang' CHECK (priority IN ('Rendah', 'Sedang', 'Tinggi')),
  order_number text,
  description text NOT NULL,
  status text NOT NULL DEFAULT 'Menunggu' CHECK (status IN ('Menunggu', 'Sedang Ditangani', 'Terselesaikan')),
  admin_notes text NOT NULL DEFAULT '',
  resolution text,
  received_at timestamp with time zone NOT NULL DEFAULT now(),
  resolved_at timestamp with time zone,
  created_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT complaints_resolved_at_check CHECK (
    (status = 'Terselesaikan' AND resolved_at IS NOT NULL AND resolution IS NOT NULL)
    OR (status <> 'Terselesaikan' AND resolved_at IS NULL)
  )
);

CREATE OR REPLACE FUNCTION public.set_complaints_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.updated_at = now();
  IF NEW.status = 'Terselesaikan' AND OLD.status <> 'Terselesaikan' THEN
    NEW.resolved_at = now();
  ELSIF NEW.status <> 'Terselesaikan' THEN
    NEW.resolved_at = NULL;
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS complaints_updated ON public.complaints;
CREATE TRIGGER complaints_updated
  BEFORE UPDATE ON public.complaints
  FOR EACH ROW EXECUTE FUNCTION public.set_complaints_updated_at();

CREATE INDEX IF NOT EXISTS complaints_received_idx
  ON public.complaints (received_at DESC);
CREATE INDEX IF NOT EXISTS complaints_status_idx
  ON public.complaints (status, received_at DESC);

ALTER TABLE public.complaints ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.complaints TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.complaints_id_seq TO service_role;

COMMIT;
