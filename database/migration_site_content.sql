-- Shared admin-managed content and registration terms acceptance.
BEGIN;

ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS terms_version integer,
  ADD COLUMN IF NOT EXISTS terms_accepted_at timestamp with time zone;

CREATE TABLE IF NOT EXISTS public.site_contents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_type text NOT NULL CHECK (content_type IN ('faq', 'food_policy', 'contact', 'terms')),
  audience text NOT NULL CHECK (audience IN ('consumer', 'supplier', 'all')),
  payload jsonb NOT NULL,
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  is_published boolean NOT NULL DEFAULT true,
  updated_by bigint REFERENCES public.users(id) ON DELETE SET NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT site_contents_audience_type_check CHECK (
    (content_type = 'contact' AND audience = 'all')
    OR (content_type <> 'contact' AND audience IN ('consumer', 'supplier'))
  ),
  CONSTRAINT site_contents_type_audience_unique UNIQUE (content_type, audience)
);

CREATE OR REPLACE FUNCTION public.set_site_contents_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.updated_at = now();
  NEW.version = OLD.version + 1;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS site_contents_updated ON public.site_contents;
CREATE TRIGGER site_contents_updated
  BEFORE UPDATE ON public.site_contents
  FOR EACH ROW EXECUTE FUNCTION public.set_site_contents_updated_at();

CREATE INDEX IF NOT EXISTS site_contents_published_idx
  ON public.site_contents (content_type, audience)
  WHERE is_published = true;

ALTER TABLE public.site_contents ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.site_contents TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.site_contents_id_seq TO service_role;

